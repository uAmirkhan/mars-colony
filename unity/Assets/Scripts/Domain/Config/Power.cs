using System.Collections.Generic;

namespace MarsColony.Domain.Config
{
    /// <summary>
    /// Энергия колонии: выработка и потребление.
    ///
    /// ВНИМАНИЕ, ПРОИСХОЖДЕНИЕ ЧИСЕЛ. В отличие от <see cref="Goods"/> и
    /// <see cref="Economy"/>, этот файл НЕ является зеркалом TypeScript-конфига:
    /// механики энергии в каркасе нет. Числа заведены в Unity-треке решением от
    /// 2026-09-01 (см. `mars-colony/loop/scene-v2/BAZA-KRITIKI-2026-09-01.md`,
    /// дефекты A3a-A3c) и здесь являются источником истины. Если энергия позже
    /// появится в каркасе — этот файл станет зеркалом, и тогда расхождение с
    /// каркасом будет багом ЭТОГО файла.
    ///
    /// Зачем энергия вообще. Счётчик kW стоял в интерфейсе без единого источника
    /// и потребителя: число росло из ниоткуда и подрывало доверие к трём честно
    /// нарисованным цепочкам. Энергия вводится НЕ как товар на продажу, а как
    /// условие работы: при дефиците производство замедляется. Так счётчик
    /// становится честным, а доменная петля «вырастил-переработал-продал»
    /// остаётся нетронутой.
    /// </summary>
    public static class Power
    {
        /// <summary>
        /// Одна солнечная станция: крыша целиком закрыта полотном батареи.
        ///
        /// Раньше здесь считалась отдельная плитка, и выработка выводилась из их
        /// числа. Заказчик забраковал плитки с просветами: крыша должна быть
        /// сплошным полотном, иначе она не читается как батарея. Поштучный счёт
        /// вместе с плитками потерял смысл — станция стала цельным объектом.
        ///
        /// Значение подобрано под СТАРТОВЫЙ ДЕФИЦИТ, а не под баланс в ноль.
        /// 64 плюс ангар 20 дают 84 против 95 потребления: не хватает
        /// одиннадцати, и это ровно одна достройка. Провал вдвое читался бы как
        /// «всё сломано» и отпугивал на первом экране, поэтому число выбрано от
        /// желаемого разрыва, а не наоборот.
        /// </summary>
        public const int STANTSIYA_KW = 64;

        /// <summary>Ангар с солнечными панелями — вторичный источник.</summary>
        public const int ANGAR_PANELI_KW = 20;

        /// <summary>
        /// Потребление по виду постройки, кВт. Ключ — префикс имени объекта в
        /// сцене: сцена собрана раскладкой по именам, отдельного реестра типов
        /// у объектов пока нет, и заводить его ради энергии избыточно.
        /// </summary>
        public static readonly Dictionary<string, int> CONSUMPTION = new Dictionary<string, int>
        {
            { "zhiloy-kupol", 4 },
            { "zhiloy-bashnya", 8 },
            { "kupol-geodezicheskiy", 5 },
            { "zavod-pishchevoy", 9 },
            { "sklad-angar", 3 },
            { "sklad-bunkery", 2 },
            // Плавильня встала на место angar-ledovoy-tehniki. Печь топит лед,
            // поэтому ест больше прежнего ангара: 6 против 4.
            { "stantsiya-plavilnya-lda", 6 },
            // Буровые вышки: карьер дает руду, ледник — метан из клатратов.
            { "burovaya-02", 8 },
            { "burovaya-05", 10 },
            // Сборщики с поверхности, не бурение: лед и реголит гребут сверху.
            // Прежние имена burovaya-03 и burovaya-04 врали о функции.
            { "mashina-ledosbor", 3 },
            { "mashina-regolitosbor", 6 },
            { "o2-skvazhina", 7 },
            { "modul-tonnelnyy", 2 },
        };

        /// <summary>
        /// Порог, ниже которого производство замедляется. Дефицит — это не
        /// проигрыш, а повод построить станцию: жёсткая остановка в казуальном
        /// сити-билдере читается как наказание и роняет удержание.
        /// </summary>
        public const double DEFICIT_SLOWDOWN = 0.5;

        /// <summary>Замедление при дефиците: во сколько раз дольше идёт цикл.</summary>
        public const double DEFICIT_FACTOR = 1.5;

        /// <summary>Хватает ли выработки. Равенство считается достаточным.</summary>
        public static bool IsEnough(int generated, int consumed) => generated >= consumed;

        /// <summary>
        /// Текущий баланс колонии. Заполняется сборщиком сцены по фактическим
        /// объектам (панели станции и список потребителей), а не задаётся руками:
        /// именно «число из ниоткуда» и было исходным дефектом A3b.
        /// </summary>
        public static int generated;
        public static int consumed;

        /// <summary>
        /// Во сколько раз дольше идёт производственный цикл при текущем балансе.
        /// Единица — если энергии хватает.
        /// </summary>
        public static double ProductionFactor() =>
            IsEnough(generated, consumed) ? 1.0 : DEFICIT_FACTOR;

        /// <summary>
        /// Какие постройки остались без питания при дефиците. Гасим с конца
        /// списка потребителей: сначала добыча, жильё отключается последним —
        /// в казуальной игре обесточенный дом читается как наказание игрока.
        /// </summary>
        public static readonly string[] SHUTDOWN_ORDER =
        {
            "mashina-ledosbor", "sklad-bunkery", "modul-tonnelnyy", "mashina-regolitosbor",
            "sklad-angar", "stantsiya-plavilnya-lda", "burovaya-02", "o2-skvazhina",
            "burovaya-05", "zavod-pishchevoy", "kupol-geodezicheskiy",
            "zhiloy-kupol", "zhiloy-bashnya",
        };
    }
}
