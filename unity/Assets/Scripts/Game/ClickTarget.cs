using UnityEngine;

namespace MarsColony.Game
{
    /// <summary>
    /// Объект сцены, который принимает нажатие.
    ///
    /// ПОЧЕМУ ПОПАДАНИЕ ПЕРЕПИСАНО НА ТРЁХМЕРНОЕ. Прежняя версия считала
    /// попадание по рамке спрайта и сравнивала только X и Y, потому что срез
    /// был плоским. Сцена колонии собрана на мешах и снимается перспективной
    /// камерой: у плоской проверки там нет ни одного шанса — она сравнивает
    /// экранную точку, переведённую в мир на плоскости ближнего отсечения, с
    /// габаритом объекта, стоящего в десятках метров глубже. Кликнуть по зданию
    /// было физически невозможно (дефект A10 в `BAZA-KRITIKI-2026-09-01.md`).
    ///
    /// Теперь область попадания — объединение габаритов ВИДИМЫХ мешей объекта,
    /// а проверка — пересечение луча из камеры с этим габаритом. Работает и в
    /// ортографии, и в перспективе, и для спрайта: у `SpriteRenderer` тоже есть
    /// `bounds`, поэтому плоский прототип продолжает работать без правок.
    ///
    /// ПРО ФИЗИКУ. Старый комментарий уверял, что модуля физики в проекте нет и
    /// потому лучи недоступны. Проверка это опровергла: `Physics.Raycast`
    /// компилируется и работает. Но он здесь и не нужен: `Bounds.IntersectRay`
    /// — чистая математика, коллайдеры ей не требуются, и сцену не надо
    /// обвешивать телами ради попадания курсора.
    ///
    /// Почему не UI-кнопка поверх здания. Здания живут в мире, а не на канвасе:
    /// кнопке пришлось бы каждый кадр пересчитывать позицию из камеры, и при
    /// любом сдвиге камеры она уезжала бы от здания — разъезд, который на кадре
    /// не виден, пока не промахнёшься.
    /// </summary>
    public abstract class ClickTarget : MonoBehaviour
    {
        /// <summary>Спрайт плоского прототипа. В трёхмерной сцене его нет.</summary>
        protected SpriteRenderer sprite;

        /// <summary>Идентификатор для моста в браузер и для отчетов проверок.</summary>
        public abstract string TargetId { get; }

        /// <summary>Человеческое имя цели — оно же в подсказке HUD.</summary>
        public abstract string Label { get; }

        protected virtual void Awake()
        {
            sprite = GetComponent<SpriteRenderer>();
        }

        /// <summary>
        /// Область попадания в мировых координатах: объединение габаритов всех
        /// включённых мешей объекта. Системы частиц исключены — их габарит
        /// раздувается по шлейфу и утащил бы область попадания в небо.
        ///
        /// Считается каждый раз, а не кэшируется: объекты сцены двигаются
        /// (техника ездит по маршруту), и устаревший габарит дал бы попадание
        /// по пустому месту — молча, без единой ошибки в консоли.
        /// </summary>
        public Bounds ClickBounds
        {
            get
            {
                var rs = GetComponentsInChildren<Renderer>(false);
                bool est = false;
                Bounds b = new Bounds(transform.position, Vector3.zero);
                foreach (var r in rs)
                {
                    if (r is ParticleSystemRenderer)
                        continue;
                    if (!est) { b = r.bounds; est = true; }
                    else b.Encapsulate(r.bounds);
                }
                return b;
            }
        }

        /// <summary>Порядок отрисовки спрайта. Нужен только плоскому прототипу.</summary>
        public int SortingOrder => sprite != null ? sprite.sortingOrder : 0;

        /// <summary>
        /// Пересекает ли луч из камеры габарит объекта. Возвращает расстояние
        /// до входа в габарит — по нему выбирается ближний из нескольких.
        /// </summary>
        public bool Popadanie(Ray luch, out float rasstoyanie)
        {
            return ClickBounds.IntersectRay(luch, out rasstoyanie);
        }

        public abstract void OnClicked(ColonyGame game, double now);

        /// <summary>Отрисовка состояния объекта. Вызывается игрой каждый кадр.</summary>
        public virtual void Render(ColonyGame game, double now) { }
    }
}
