/**
 * Соседние деревья: спеки в `../wiki` и Unity-зеркало в `../mars-unity`.
 *
 * Две проверки в гейте читают файлы ЗА пределами репозитория: сверку чисел с
 * C#-зеркалом и сверку имен параметров со спекой. На машине разработки соседи
 * есть, и обе идут. У любого, кто взял один репозиторий, — нет, и обе падали
 * с `ENOENT`. Первым это поймала публикация: ворота, зеленые локально, на
 * чистой машине не проходят вовсе.
 *
 * Решение — пропуск, но ГРОМКИЙ. Пропущенная проверка обязана выглядеть
 * пропущенной, а не зеленой: `describe.skipIf` показывает ее отдельной
 * строкой, плюс в вывод уходит предупреждение с причиной. Молчаливый пропуск
 * тут был бы хуже красного — он рассказывает, что сверка идет, когда ее нет.
 *
 * Почему не скопировать спеки внутрь репозитория: они живут в вики одним
 * экземпляром, а копия расходится с оригиналом молча — ровно тот класс, от
 * которого эти две проверки и защищают.
 */

import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

/** Корень рабочего дерева: на уровень выше самого репозитория. */
export const WORKSPACE = join(HERE, '../../../..');

export const CS_MIRROR_ROOT = join(WORKSPACE, 'mars-unity/Assets/Scripts/Domain');
export const SPEC_ROOT = join(WORKSPACE, 'wiki/saas/projects/mars-colony');

let warned = false;

/**
 * Есть ли сосед на диске. Первый отрицательный ответ печатает причину: без
 * этой строки пропуск выглядел бы как «тестов просто нет».
 */
export function siblingExists(path: string, what: string): boolean {
  if (existsSync(path)) return true;
  if (!warned) {
    warned = true;
    console.warn(
      `\nВНИМАНИЕ: ${what} не найден по пути ${path}.\n` +
        'Проверки, сверяющие код с соседними деревьями, ПРОПУЩЕНЫ.\n' +
        'Это ожидаемо вне рабочей машины: спеки и Unity-зеркало лежат рядом с\n' +
        'репозиторием, а не внутри него. На машине разработки они обязаны идти.\n',
    );
  }
  return false;
}
