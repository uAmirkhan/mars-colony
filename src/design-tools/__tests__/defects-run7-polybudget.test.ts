/**
 * Прогон 7 — доказательство дефекта (ломатель), число из плана против числа
 * из кода.
 *
 * `loop/run-7/plan.md`, раздел "Что известно про партию до начала":
 * "Геометрия приезжает по 470-500 тысяч треугольников. Режем до 20 тысяч; на
 * 4 тысячах форма разваливается, проверено рендерами
 * (`design/models/osmotr/`)." То есть план целится в диапазон децимации
 * (4000, 20000] треугольников на модель.
 *
 * `design/tools/check-model.mjs`, `verdict()`: `стоп` при `tris > 12000`,
 * `правка` при `tris > 4000`. Верхняя граница приемки — 12000, а не 20000.
 *
 * Пересечение двух диапазонов — (4000, 12000], а не (4000, 20000], как
 * читается из плана. Если модель срежут ровно до заявленной в плане цели
 * (около 20 тысяч), `check-model.mjs` отклонит ее по тому же основанию, по
 * которому сейчас отклоняет сырую геометрию — числом треугольников, просто
 * меньшим. Свежая децимация станет "готовой" по плану и "стоп" по приемке
 * одновременно.
 *
 * Доказательство не гипотетическое: в `design/models/` уже лежит
 * `shuttle-20000.glb` — файл, чье имя и есть заявленная цель децимации, и
 * фактический поликаунт (19669) почти точно ей равен. Ниже — прогон
 * действующей приемки на этом самом файле.
 *
 * Не дефект кода `check-model.mjs` сам по себе (порог 12000 откалиброван
 * под вес веб-плеера и объяснен в комментарии) — а нестыковка ЧИСЕЛ между
 * планом узла и его же инструментом приемки. К узлу 2 ("Внедрение") это
 * бьет напрямую: если программист срежет партию до цели плана, приемка
 * завернет партию целиком по числу, названному тем же планом безопасным.
 */

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..', '..');
const CHECK_MODEL = join(REPO_ROOT, 'design', 'tools', 'check-model.mjs');
// Единственный файл партии, уже децимированный примерно до заявленной в
// плане цели (~20 тысяч треугольников) — фактическое число внутри 19669.
const SHUTTLE_20000 = join(REPO_ROOT, 'design', 'models', 'shuttle-20000.glb');

const filesPresent = existsSync(SHUTTLE_20000) && existsSync(CHECK_MODEL);

describe.skipIf(!filesPresent)(
  'Дефект: цель децимации плана (~20 тысяч) не проходит порог check-model.mjs (12 тысяч)',
  () => {
    it('shuttle-20000.glb (19669 тр., заявленная планом цель) обязан пройти приемку по треугольникам, но не проходит', () => {
      const proc = spawnSync(process.execPath, [CHECK_MODEL, SHUTTLE_20000], {
        encoding: 'utf8',
        cwd: REPO_ROOT,
      });
      const stdout = proc.stdout ?? '';

      // Число подтверждено фактическим прогоном инструмента (см.
      // design/models/shuttle-20000-intake.json, поле measured.tris).
      expect(stdout).toContain('19669 треугольников');

      // ГЛАВНОЕ УТВЕРЖДЕНИЕ. Если бы план и приемка были согласованы по
      // числу, децимация ровно до заявленной планом цели проходила бы без
      // "стоп". Сейчас — не проходит: код завершается кодом 1.
      expect(proc.status).toBe(0);
    });
  },
);
