/**
 * Прогон 7 — доказательство дефекта (ломатель).
 *
 * `design/tools/check-model.mjs` ловит вырождение только одним числом:
 * отношение наименьшего габарита к наибольшему ("тонкость", `verdict()`,
 * ветка "объект расплющен"). Порог 0.15 калиброван так, чтобы не заворачивать
 * честно низкие объекты набора (площадка, тайлы грунта).
 *
 * Дефект "плита" тоньше не делает габарит — он делает объект МАЛЫМ ОТНОСИТЕЛЬНО
 * СВОЕЙ ЖЕ ПОДЛОЖКИ. Генератор восстановил из фотографии плоский постамент, и
 * настоящее здание занимает малую долю пятна застройки, а сам постамент дает
 * габариту достаточную высоту, чтобы тонкость выглядела здоровой. Тонкость
 * меряет форму КОРОБКИ, а не то, чем коробка заполнена — этого числа в
 * `check-model.mjs` нет вообще, ни в `measureGltf()`, ни в `verdict()`.
 *
 * `zhiloy-bashnya`: тонкость 0.692 (лучшее число в списке "годны" по замеру
 * оркестратора, `loop/run-7/plan.md`) при доле пятна застройки 0.06 — то
 * есть под геометрией выше четверти высоты занято 6% площади опоры. Число
 * подтверждено дважды независимо: `design/tools/plita.py` в Blender 5.2 дает
 * тонкость 0.692 / долю 0.06 (`loop/run-7/tester-work.md`), и повторный
 * пересчет тем же способом, но без Blender — прямым разбором GLB
 * (`glb-footprint.ts`, копия матричной математики `check-model.mjs`) — дает
 * тонкость 0.6920 / долю 0.0551. Совпадение до третьего знака.
 *
 * Падающая проверка ниже не чинит `check-model.mjs` (не моя роль) — она
 * фиксирует, что модель с такими числами ДОЛЖНА получить отдельную заметку о
 * подложке/пятне застройки, а СЕЙЧАС не получает ни одной: только штраф за
 * поликаунт (не относится к делу, снимается децимацией) и заметка про
 * встроенную текстуру. Ни одна строка вывода не упоминает долю, подложку или
 * пятно. Красный тест = дыра в приемке, а не поправка ожидания под код.
 */

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { footprintOccupancy } from './glb-footprint';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..', '..');
const CHECK_MODEL = join(REPO_ROOT, 'design', 'tools', 'check-model.mjs');
const MODEL = join(REPO_ROOT, 'design', 'models', 'zhiloy-bashnya.glb');

const modelPresent = existsSync(MODEL) && existsSync(CHECK_MODEL);

describe.skipIf(!modelPresent)(
  'Дефект: check-model.mjs не ловит "плиту" — объект на подложке (run-7)',
  () => {
    it('zhiloy-bashnya проходит по тонкости, но занимает 6% пятна застройки — приемка обязана это заметить', () => {
      // Независимый замер (без Blender, прямой разбор GLB тем же порядком
      // матриц, что в check-model.mjs — см. glb-footprint.ts).
      const { thinness, dolya } = footprintOccupancy(MODEL);

      // Контрольные числа плана (2026-08-09): тонкость 0.692, доля 0.06.
      // Допуск широкий: важно не совпадение до знака, а порядок величины.
      expect(thinness).toBeGreaterThan(0.5); // объемный габарит — не блин
      expect(dolya).toBeLessThan(0.15); // но настоящий объект — маленький на подложке

      const proc = spawnSync(process.execPath, [CHECK_MODEL, MODEL], {
        encoding: 'utf8',
        cwd: REPO_ROOT,
      });
      const stdout = proc.stdout ?? '';

      // Блин-детектор (порог тонкости 0.15) должен молчать — это ожидаемо и
      // не проверка дефекта, а подтверждение того, что "плита" и "блин" — два
      // разных дефекта с разными числами, а не один и тот же случай.
      expect(stdout).not.toMatch(/вырождена|расплющен/);

      // ГЛАВНОЕ УТВЕРЖДЕНИЕ. Приемка обязана иметь строку про долю пятна
      // застройки / подложку для модели с такими числами. Сейчас в
      // check-model.mjs такой проверки нет ни в одном месте verdict() —
      // значит утверждение ниже красное, и это доказательство дефекта, а не
      // ошибка теста.
      const catchesPedestal = /долю|доля|подложк|пятн[оа]|плита/i.test(stdout);
      expect(catchesPedestal).toBe(true);
    });
  },
);
