/**
 * Что видит человек, открывший ссылку.
 *
 * Три случая и одно правило на каждый:
 *   - пришел впервые -> показ (колония седьмого уровня, рейс на подлете);
 *   - уже играл -> его собственный сейв, показ не навязывается;
 *   - хочет с нуля -> `?fresh=1` стирает сейв и начинает канонический старт.
 *
 * Почему показ по умолчанию, а не канонический старт. Ссылку открывают на
 * несколько минут. С нуля до шаттла идти часы, и шаттл — то, ради чего вся
 * ссылка, — в такую сессию не попадает вовсе. Начало с нуля при этом остается
 * доступным одним переключателем: показ не прячет игру, он только выбирает,
 * с какой точки ее показать.
 *
 * Почему решение принимается здесь, до отрисовки, а не внутри компонента.
 * Сейв поднимается синхронно при импорте стора, и первый кадр рисуется уже с
 * ним. Подстановка показа из `useEffect` дала бы видимую вспышку чужого
 * состояния — колония первого уровня на четверть секунды.
 */

import { applyDemoState, demoFailure } from './demo';
import { createInitialState, SAVE_KEY, saveAccepted, useGame } from './gameStore';

export type EntryMode = 'demo' | 'saved' | 'fresh';

/**
 * Отметка «это состояние собрано показом».
 *
 * Дефект Д-30: после перезагрузки подпись показа исчезала, а выданные числа
 * оставались. Человек видел колонию седьмого уровня с тысячей изотопов и ни
 * слова о том, откуда они. Молчание здесь читается как «все заработано» —
 * ровно то вранье, против которого подпись и написана.
 *
 * Отдельный ключ, а не поле сейва: формат сейва проверяется по составу полей,
 * и новое поле потребовало бы поднять версию, то есть выбросить сейвы всех,
 * кто уже играет. Цена не стоит одного флага.
 */
const DEMO_MARK_KEY = 'mars-colony-demo';

/**
 * Куда пишется показ, открытый поверх ЧУЖОЙ игры. Отдельный ключ нужен ровно
 * для того, чтобы витрина не затирала колонию, до которой человек шел часами.
 */
const DEMO_SAVE_KEY = 'mars-colony-demo-save';

function markDemo(): void {
  try {
    localStorage.setItem(DEMO_MARK_KEY, '1');
  } catch {
    // Хранилище запрещено: подпись покажется в этой сессии и не переживет
    // перезагрузку. Это хуже, чем ничего, но лучше, чем упасть.
  }
}

function clearDemoMark(): void {
  try {
    localStorage.removeItem(DEMO_MARK_KEY);
  } catch {
    // Нечего стирать или не дали.
  }
}

/**
 * Снять разовую метку с адреса.
 *
 * Метки входа одноразовые по смыслу: они говорят, ЧЕМ открыть страницу, а не
 * чем открывать ее всегда. Оставшаяся в адресе метка повторяет свое действие
 * при каждом обновлении — и `fresh`, и `demo` при этом стирают то, что человек
 * успел сделать.
 */
function dropParam(name: string): void {
  try {
    const url = new URL(window.location.href);
    if (!url.searchParams.has(name)) return;
    url.searchParams.delete(name);
    window.history.replaceState(null, '', url.toString());
  } catch {
    // Переписать адрес не дали: поведение остается прежним, игра работает.
  }
}

function demoMarked(): boolean {
  try {
    return localStorage.getItem(DEMO_MARK_KEY) !== null;
  } catch {
    return false;
  }
}

function param(name: string): boolean {
  if (typeof window === 'undefined') return false;
  return new URLSearchParams(window.location.search).has(name);
}

/**
 * Был ли у человека прогресс до этого захода.
 *
 * Спрашиваем у стора, принял ли он сейв, а не у `localStorage`, лежит ли там
 * что-нибудь. Разница несущая. Прямое чтение врет всегда: загрузка страницы
 * делает шаг времени, шаг пишет состояние, и запись в ключе есть уже к моменту
 * проверки даже у того, кто зашел впервые. А еще в ключе может лежать мусор,
 * чужой объект или сейв неизвестной версии — для игры это все то же самое, что
 * пустота: играть не с чего, значит заход первый.
 */
function hasSave(): boolean {
  return saveAccepted();
}

/** Стереть сохранение и начать канонический старт. Вызывается кнопкой. */
export function startFresh(): void {
  try {
    localStorage.removeItem(SAVE_KEY);
  } catch {
    // Нечего стирать или не дали: перезагрузка ниже все равно уместна.
  }
  // Перезагрузка, а не подстановка состояния: сброс обязан пройти тот же путь,
  // что и первый заход человека, иначе «с нуля» проверяется не тем кодом.
  const url = new URL(window.location.href);
  url.searchParams.delete('demo');
  url.searchParams.set('fresh', '1');
  window.location.replace(url.toString());
}

/** Открыть показ поверх текущего состояния. Вызывается кнопкой. */
export function startDemo(): void {
  const url = new URL(window.location.href);
  url.searchParams.delete('fresh');
  url.searchParams.set('demo', '1');
  window.location.replace(url.toString());
}

let mode: EntryMode = 'saved';

/** Каким состоянием открылась страница. Нужно подписи на экране. */
export function entryMode(): EntryMode {
  return mode;
}

/**
 * Выбрать состояние старта. Зовется ровно один раз, до первой отрисовки.
 * Возвращает выбранный режим — вызывающему это нужно только для журнала.
 */
export function chooseEntryState(): EntryMode {
  // Ключ сейва назначается ЯВНО и на каждом заходе, а не переключается по
  // ходу дела. Показ поверх чужой игры пишется в отдельный ключ (см. ниже), и
  // если бы переключение было односторонним, оно пережило бы сам заход:
  // следующий вызов писал бы витрину туда же, куда и предыдущий. В браузере
  // страница загружается один раз и разницы не видно, а вот проверки на общем
  // сторе ловят это сразу — и ловят справедливо.
  useGame.persist?.setOptions?.({
    name: param('demo') && hasSave() ? DEMO_SAVE_KEY : SAVE_KEY,
  });

  if (param('fresh')) {
    // Стирается И хранилище, И состояние в памяти.
    //
    // Дефект Д-26: чистка одного хранилища не сбрасывала ничего. Стор
    // поднимает сейв синхронно при импорте — то есть ДО этой строки, — и
    // прогресс уже сидит в памяти. Следующая же запись возвращала его в
    // только что очищенный ключ, и человек, перешедший по ссылке «начать
    // заново», оказывался в той же колонии, из которой уходил. Кнопка
    // «Начать с нуля» дефект прикрывала: она удаляет ключ ДО перезагрузки.
    useGame.persist?.clearStorage?.();
    clearDemoMark();
    // Запись канонического старта обязательна. Пустое хранилище для
    // следующего захода неотличимо от первого визита, а первый визит — это
    // показ: человек нажал «начать с нуля», обновил страницу и получил бы
    // ту самую колонию седьмого уровня, от которой уходил.
    useGame.setState({ ...createInitialState(), now: Math.floor(Date.now() / 1000) });
    // Метка снимается с адреса сразу же. Иначе обновление страницы стирало бы
    // прогресс каждый раз: человек нажал «с нуля» один раз, а получил экран,
    // который забывает его при каждом F5.
    dropParam('fresh');
    mode = 'fresh';
    return mode;
  }

  if (param('demo') || !hasSave()) {
    // Ключ уже выбран выше: у человека со своей игрой показ пишется в
    // отдельный (вторая половина Д-27) — иначе колония, до которой он шел
    // часами, молча заменялась бы витриной, и вернуться было бы некуда. У
    // пришедшего впервые ключ обычный: тогда показ и есть его игра, и она
    // обязана пережить перезагрузку.
    mode = applyDemoState() ? 'demo' : 'fresh';
    if (mode === 'demo') markDemo();
    else {
      // Откат на канонический старт — не штатная ветка, а провал витрины.
      // Он обязан быть слышен: без этой строки ссылка открывается пустым
      // первым уровнем, и отличить «показ не собрался» от «так и задумано»
      // нельзя ничем, кроме глаз. В этом проекте такое уже стоило дня.
      console.error(`[показ] состояние не собрано, откат на первый заход: ${demoFailure()}`);
    }
    // Метка снимается с адреса ровно по той же причине, что и у `fresh`
    // (дефект Д-27). Оставшийся в адресе `?demo=1` пересобирает показ на
    // КАЖДОМ обновлении страницы: человек поиграл, нажал F5 и потерял все,
    // что успел сделать. Своего сейва под этим ключом к тому моменту уже нет
    // — показ его перезаписал, — то есть вернуться некуда.
    dropParam('demo');
    return mode;
  }

  // Сейв, выросший из показа, остается показом. Числа-то выданные никуда не
  // делись, а объяснение им дает только подпись.
  mode = demoMarked() ? 'demo' : 'saved';
  return mode;
}
