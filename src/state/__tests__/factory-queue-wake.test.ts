/**
 * Сторож: слот фабрики в очереди просыпается на КАЖДОМ пути, где растет
 * доступный остаток склада, а не только на сборе урожая.
 *
 * Дефект Д-19 прогона 3: будильник `onWarehouseStockIncreased` звали ровно два
 * действия — сбор с грядки и сбор с фабрики. Но доступный остаток растет и
 * когда игрок выбрасывает заказ дрона: `releaseReserved` снимает резерв, и для
 * склада это ровно то же событие, что урожай. Слот в очереди этого не видел и
 * голодал бессрочно, имея нужный товар физически на полке.
 *
 * Тест живет в гейте, а не среди доказательств: он зеленый и его работа —
 * не дать дефекту вернуться. Класс уже возвращался однажды внутри самой
 * `onWarehouseStockIncreased` (ранняя остановка цикла), поэтому сторож нужен.
 *
 * Проверка ведется через стор, а не через домен, сознательно. Склад — чистая
 * структура данных и про производство не знает; связывает их тонкая обертка
 * состояния (`mars-colony/CLAUDE.md`, раздел «Архитектура»). Доменное
 * доказательство Д-19 требует, чтобы будил сам `unreserve`, — это другой
 * контракт, и вопрос о нем записан в реестр.
 */

import { describe, expect, it } from 'vitest';
import { deposit } from '../../domain/warehouse';
import { useGame } from '../gameStore';

describe('очередь фабрики просыпается на освобождении резерва', () => {
  it('выброс заказа дрона поднимает слот из очереди в производство', () => {
    // Уровень и кредиты — чтобы фабрика была доступна и по карману. Числа
    // берутся с запасом: тест про пробуждение слота, а не про цену здания.
    useGame.setState({ level: 21, credits: 100_000 });
    useGame.getState().buyBuilding('food_module');

    const slots = useGame.getState().factory_slots;
    expect(slots.length, 'фабрика должна быть куплена').toBeGreaterThan(0);

    // Сырье на складе есть, но целиком занято заказом дрона: доступного ноль.
    const warehouse = useGame.getState().warehouse;
    deposit(warehouse, 'soy', 8);
    useGame.setState({ warehouse: { ...warehouse } });

    // Заказ на сою ставим руками: доска наполняется тиком по расписанию, а тест
    // про пробуждение слота, а не про генератор.
    useGame.setState({
      orders: [
        {
          idx: 0,
          state: 'active' as const,
          npc_name: 'тест',
          positions: [
            { good_id: 'soy' as const, qty: 8, filled: false, filled_by: null, easy: true },
          ],
          credits_reward: 10,
          xp_reward: 1,
          refresh_at: 0,
        },
      ],
    });

    // Грузим со склада штатным путем — именно он создает резерв.
    useGame.getState().loadOrderPosition(0, 0);

    // Ставим в очередь то, на что входов сейчас не хватает.
    useGame.getState().enqueue(0, 'protein_bar');
    expect(
      useGame.getState().factory_slots[0]?.state,
      'слот обязан ждать в очереди: доступного сырья нет',
    ).toBe('QUEUED');

    // Выброс заказа возвращает сою в доступные. Для склада это ровно то же
    // событие, что урожай, и слот обязан на него проснуться.
    useGame.getState().discardOrderAt(0);

    expect(useGame.getState().factory_slots[0]?.state, 'слот голодает при сырье на полке').toBe(
      'PRODUCING',
    );
  });
});
