/**
 * Состояние показа обязано собираться ВСЕГДА.
 *
 * Показ — первое, что видит человек, открывший ссылку. Если сборка сорвалась,
 * `applyDemoState` честно возвращает `false`, точка входа откатывается на
 * канонический старт, и вместо колонии седьмого уровня с рейсом на подлете
 * гость получает пустой первый уровень. Игра при этом работает, ничего не
 * падает, консоль чиста — то есть провал невидим ничем, кроме глаз.
 *
 * Почему проверять надо МНОГО раз, а не один. Показ строится не рисованием
 * сейва, а прогоном настоящих действий игры, и рейс ему выдает настоящий
 * генератор — со случайностью. Одиночная проверка отвечает на вопрос «сработало
 * ли на этом рейсе», а нужен ответ на «срабатывает ли на любом».
 *
 * Так и нашелся дефект: генератор иногда выдает два отсека под ОДИН товар, а
 * сборщик докладывал товар на склад по общему остатку, не вычитая то, что уже
 * зарезервировал первый отсек. Второй отсек не закрывался, рейс не улетал,
 * показа не было. Браузерные проверки падали «через раз» и каждый раз на
 * разном тесте — классическая картина, за которой ищут флаки в самой проверке,
 * а не дефект в коде.
 */

import { beforeEach, describe, expect, it } from 'vitest';
import { applyDemoState, DEMO_LEVEL } from '../demo';
import { createInitialState, useGame } from '../gameStore';

/** Сколько раз собрать показ. Каждый прогон — свой случайный рейс. */
const RUNS = 80;

describe('Состояние показа', () => {
  beforeEach(() => {
    useGame.setState({ ...createInitialState(), now: Math.floor(Date.now() / 1000) });
  });

  it(`собирается ${RUNS} раз подряд, на любом выпавшем рейсе`, () => {
    const failed: number[] = [];
    for (let i = 0; i < RUNS; i++) {
      if (!applyDemoState()) failed.push(i);
    }
    expect(
      failed,
      `сборка показа сорвалась на прогонах ${failed.join(', ')} из ${RUNS}. ` +
        `Ссылка в этих случаях открывается пустым первым уровнем.`,
    ).toEqual([]);
  });

  it('после сборки на экране действительно колония показа, а не заглушка', () => {
    expect(applyDemoState()).toBe(true);
    const state = useGame.getState();

    expect(state.level, 'уровень колонии показа').toBe(DEMO_LEVEL);
    expect(state.shuttle?.state, 'рейс обязан быть в пути, иначе показывать нечего').toBe(
      'IN_TRANSIT',
    );
    expect(
      state.fields.some((f) => f.state === 'READY'),
      'хотя бы одна грядка созрела: гостю нужно немедленное действие, а не ожидание',
    ).toBe(true);
    expect(state.toasts, 'сборка не должна оставлять после себя всплывающих сообщений').toEqual(
      [],
    );
  });
});
