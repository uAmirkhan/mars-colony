/**
 * Публикация играбельной сборки: `node publish.mjs`.
 *
 * Исходники, заметки цикла, отчеты проверяющих и списки вырезанного лежат в
 * ПРИВАТНОМ репозитории и никуда не уезжают. Наружу идет только собранная
 * папка `dist` — отдельным публичным репозиторием, из которого GitHub Pages
 * отдает страницу. Такой разрез выбран владельцем 2026-08-06: бесплатный
 * тариф не отдает Pages из приватного репозитория, а делать публичным весь
 * рабочий процесс он не захотел.
 *
 * Почему скриптом с машины, а не действием на сервере: чужой репозиторий с
 * сервера не запишешь без отдельного токена, а токен ради одной команды —
 * лишний секрет, который потом надо где-то хранить и когда-то отзывать.
 *
 * Что делает:
 *   1. гоняет те же ворота, что и коммит: формат, типы, тесты;
 *   2. собирает с префиксом адреса Pages;
 *   3. кладет `dist` в отдельное рабочее дерево и пушит одним коммитом.
 *
 * Ворота здесь не формальность. На страницу не должно уехать то, что не
 * проходит проверку у нас, — иначе публикация станет способом обойти гейт.
 */

import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const REPO = 'https://github.com/uAmirkhan/mars-colony-play.git';
const PAGES_BASE = '/mars-colony-play/';
const BRANCH = 'main';

/**
 * Запуск команды.
 *
 * `shell` включен только для `npm`: на Windows это батник, и без оболочки он
 * не запускается. Для `git` оболочка ВРЕДНА — она режет аргументы по пробелам,
 * и сообщение коммита из двух слов превращается в два аргумента. Первая версия
 * скрипта на этом и споткнулась, причем споткнулась молча: падение коммита
 * выглядело как «нечего публиковать».
 */
function run(cmd, args, opts = {}) {
  console.log(`> ${cmd} ${args.join(' ')}`);
  execFileSync(cmd, args, { stdio: 'inherit', shell: cmd === 'npm', ...opts });
}

/** Есть ли что публиковать. Спрашиваем прямо, а не угадываем по падению. */
function hasChanges(cwd) {
  return execFileSync('git', ['status', '--porcelain'], { cwd, encoding: 'utf8' }).trim() !== '';
}

// 1. Ворота. Падение здесь означает, что публиковать нечего.
run('npm', ['run', 'check']);

// 2. Сборка с префиксом Pages. Локальная сборка живет с корневым префиксом,
//    поэтому переменная задается только здесь.
run('npm', ['run', 'build'], { env: { ...process.env, PAGES_BASE } });

if (!existsSync('dist/index.html')) {
  console.error('нет dist/index.html: сборка не дала результата');
  process.exit(2);
}

// 3. Отдельное рабочее дерево. Клонируем начисто каждый раз: так исключено,
//    что в публикацию попадет что-то, оставшееся с прошлого прогона.
const work = mkdtempSync(join(tmpdir(), 'mars-play-'));
try {
  run('git', ['clone', '--depth', '1', REPO, work]);
} catch {
  // Пустой репозиторий клонируется с предупреждением и без ветки — это норма
  // для первой публикации.
  run('git', ['init', '-b', BRANCH, work]);
  run('git', ['remote', 'add', 'origin', REPO], { cwd: work });
}

// Старое содержимое стирается целиком, кроме служебной папки git: страница
// обязана быть ровно тем, что собралось сейчас, без следов прошлых сборок.
for (const entry of ['assets', 'index.html', 'favicon.svg', '.nojekyll', 'vite.svg']) {
  rmSync(join(work, entry), { recursive: true, force: true });
}

cpSync('dist', work, { recursive: true });

// Pages по умолчанию прогоняет содержимое через Jekyll, а тот выбрасывает
// папки и файлы, начинающиеся с подчеркивания. Метка отключает обработку.
writeFileSync(join(work, '.nojekyll'), '');

run('git', ['add', '-A'], { cwd: work });

if (!hasChanges(work)) {
  console.log('нечего публиковать: сборка не отличается от выложенной');
  process.exit(0);
}

// Падение коммита здесь — настоящая ошибка, и она обязана уронить скрипт.
// Ловить ее в `catch` и называть «нечего публиковать» значит врать самому
// себе: ровно так первая версия отчиталась об успехе, ничего не выложив.
run(
  'git',
  ['-c', 'user.name=publish', '-c', 'user.email=publish@local', 'commit', '-q', '-m', 'Сборка игры'],
  { cwd: work },
);
run('git', ['-c', 'http.version=HTTP/1.1', 'push', '-u', 'origin', `HEAD:${BRANCH}`], { cwd: work });

console.log(`\nвыложено: https://uamirkhan.github.io/mars-colony-play/`);
