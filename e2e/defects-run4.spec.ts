import { expect, type Page, test } from '@playwright/test';

/**
 * Браузерные доказательства прогона 4.
 *
 * Здесь то, чего модульный тест не видит: настоящий localStorage, настоящая
 * навигация и настоящая верстка. Оба дефекта ниже живут ровно на этих стыках —
 * один в переходе между двумя адресами, второй в кнопках, которых по ТЗ на
 * экране быть не должно.
 */

type Store = {
  getState: () => Record<string, unknown>;
  setState: (patch: Record<string, unknown>) => void;
};

const level = (page: Page) =>
  page.evaluate(
    () =>
      ((window as unknown as { __game: Store }).__game.getState() as unknown as { level: number })
        .level,
  );

/**
 * Д-26. `?fresh=1` — документированный способ начать с нуля («хочет с нуля ->
 * `?fresh=1` стирает сейв и начинает канонический старт», заголовок
 * `src/state/entry.ts`). Если в хранилище уже лежит сейв, адрес не сбрасывает
 * ничего: стор поднял сейв синхронно при импорте, `chooseEntryState` чистит
 * только ХРАНИЛИЩЕ, а следующая же запись возвращает поднятый прогресс обратно
 * в очищенный ключ.
 *
 * Что видит человек: перешел по ссылке «начать заново» — и оказался в той же
 * колонии, из которой уходил. Метка при этом снимается с адреса, подпись показа
 * не рисуется, и сигнала о том, что сброса не было, нет никакого.
 *
 * Почему кнопка «Начать с нуля» это скрывает: `startFresh` удаляет ключ ДО
 * перезагрузки, то есть прикрывает дефект снаружи. Весь набор браузерных
 * проверок открывает игру этим же адресом и держится на том, что хранилище
 * пустое.
 */
test('Д-26: ?fresh=1 не сбрасывает игру, если сейв уже есть', async ({ page }) => {
  // Первый заход без параметров — показ седьмого уровня, он же и сейв.
  await page.goto('/');
  await page.getByRole('button', { name: 'Играть' }).click();
  expect(await level(page), 'предпосылка: ссылка открылась показом').toBeGreaterThan(1);

  // Второй заход по документированному адресу сброса.
  await page.goto('/?fresh=1');
  await page.getByRole('button', { name: 'Играть' }).click();

  expect(await level(page), '?fresh=1 обязан открыть канонический старт').toBe(1);
});

/**
 * Д-29. Закрытый отсек рейса открывает то же окно, что и незакрытый, и рисует в
 * нем две кнопки: «Погрузить» (активна, при тапе отвечает «Нет на складе») и
 * «Докупить 0 за 0 ⚛».
 *
 * ТЗ шаттла 6.2 задает для этого состояния отдельный вид: `loaded` — «read-only
 * "Погружено: {qty}" без кнопок действия, только лупа для справки», и отдельной
 * строкой в Edge: «отмены погруженного (`loaded`) отсека UI не предоставляет».
 * Ни одной кнопки действия там быть не должно.
 *
 * Что видит игрок: тап по отсеку с галочкой предлагает купить ноль единиц за
 * ноль изотопов. Соседняя «Погрузить» выглядит рабочей и молча отвечает
 * предупреждением про пустой склад, хотя склад тут ни при чем.
 */
test('Д-29: закрытый отсек предлагает «Докупить 0 за 0»', async ({ page }) => {
  await page.goto('/?fresh=1');
  await page.getByRole('button', { name: 'Играть' }).click();

  await page.evaluate(() => {
    const store = (window as unknown as { __game: Store }).__game;
    store.setState({
      level: 9,
      credits: 100_000,
      isotopes: 100_000,
      // Пять водорослей уже лежат в отсеке: qty на месте, резерв держит отсек.
      warehouse: { capacity: 500, cells: { algae: { qty: 5, reserved: 5 } } },
      shuttle_arrivals: 1,
      shuttle: {
        state: 'ORDER',
        slots: [
          {
            idx: 0,
            good_id: 'algae',
            qty_required: 5,
            qty_filled: 5,
            qty_purchased: 0,
            filled_by: 'self',
            reward: null,
            collected: false,
            floor_forced: false,
          },
          {
            idx: 1,
            good_id: 'soy',
            qty_required: 4,
            qty_filled: 0,
            qty_purchased: 0,
            filled_by: null,
            reward: null,
            collected: false,
            floor_forced: false,
          },
        ],
        trip_min: 75,
        departed_at: 0,
        arrives_at: 0,
        cooldown_until: 0,
        is_first_trip: false,
        arrival_no: 2,
      },
    });
  });

  await page.getByRole('button', { name: 'Шаттл' }).click();
  // Закрытый отсек показан галочкой — по ней и открывается его карточка.
  await page.getByRole('button', { name: /✓/ }).click();

  await expect(
    page.getByRole('button', { name: /^Докупить/ }),
    'ТЗ 6.2, состояние loaded: кнопок действия нет вовсе',
  ).toHaveCount(0);
  await expect(
    page.getByRole('button', { name: /^Погрузить/ }),
    'догружать закрытый отсек нечем — кнопки быть не должно',
  ).toHaveCount(0);
});

/**
 * Д-30. После первой же перезагрузки подпись показа исчезает вместе с
 * единственной кнопкой «Начать с нуля», а выданные показом числа остаются.
 *
 * `DemoBadge` рисуется только при `entryMode() === 'demo'`. На втором заходе
 * сейв показа уже лежит в хранилище, режим становится `saved` — подпись
 * пропадает. Колония при этом та же самая: тысяча выданных изотопов, выданный
 * склад, выданные модули стройки.
 *
 * Два следствия, и оба несущие.
 *
 * Честность. Подпись существует ровно затем, чтобы отличить «экономика
 * начислила» от «показу выдали» («граница честности» — заголовок
 * `demo-badge.tsx`). После F5 объяснения нет, а объясняемые числа на месте.
 *
 * Выход. Кнопка «Начать с нуля» живет только внутри этой подписи и больше нигде
 * во всем интерфейсе. Вместе с Д-26 (адрес `?fresh=1` не сбрасывает поднятый
 * сейв) это значит, что после одной перезагрузки канонический старт недостижим
 * вообще ничем: ни кнопкой, ни ссылкой.
 */
test('Д-30: после перезагрузки показ остается, а объяснение и выход исчезают', async ({
  page,
}) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Играть' }).click();
  await expect(page.getByTestId('demo-badge'), 'предпосылка: первый заход подписан').toBeVisible();

  await page.reload();
  await page.getByRole('button', { name: 'Играть' }).click();

  // Колония та же — значит и подпись к ней обязана остаться.
  expect(await level(page), 'предпосылка: показ пережил перезагрузку').toBeGreaterThan(1);
  await expect(
    page.getByRole('button', { name: 'Начать с нуля' }),
    'единственный выход к каноническому старту не имеет права исчезать',
  ).toHaveCount(1);
});
